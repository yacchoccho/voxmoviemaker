//! Development-only inventory generator. Never shipped as the application.
use serde_json::Value;
use std::{
    collections::{BTreeMap, HashSet},
    error::Error,
    fs,
    path::{Path, PathBuf},
    process::Command,
};

fn notices(
    directory: &Path,
    root: &Path,
    depth: u32,
    found: &mut Vec<PathBuf>,
) -> std::result::Result<(), Box<dyn Error>> {
    if depth > 4 {
        return Ok(());
    }
    for entry in fs::read_dir(directory)? {
        let entry = entry?;
        let kind = entry.file_type()?;
        let name = entry.file_name().to_string_lossy().to_ascii_lowercase();
        if kind.is_file()
            && (name.starts_with("license")
                || name.starts_with("licence")
                || name.starts_with("copying")
                || name.starts_with("notice")
                || name == "copyright")
        {
            found.push(entry.path().strip_prefix(root)?.to_path_buf());
        } else if kind.is_dir() && ![".git", "target", "tests", "examples"].contains(&name.as_str())
        {
            notices(&entry.path(), root, depth + 1, found)?;
        }
    }
    Ok(())
}
fn main() -> std::result::Result<(), Box<dyn Error>> {
    let output = Command::new("cargo")
        .args([
            "metadata",
            "--locked",
            "--format-version",
            "1",
            "--filter-platform",
            "x86_64-unknown-linux-gnu",
        ])
        .output()?;
    if !output.status.success() {
        return Err(String::from_utf8_lossy(&output.stderr).into_owned().into());
    }
    let metadata: Value = serde_json::from_slice(&output.stdout)?;
    // metadata includes optional resolution entries. cargo tree determines what Linux actually builds.
    let tree = Command::new("cargo")
        .args([
            "tree",
            "--locked",
            "--target",
            "x86_64-unknown-linux-gnu",
            "--prefix",
            "none",
            "--format",
            "{p}",
            "-e",
            "normal,build,dev",
        ])
        .output()?;
    if !tree.status.success() {
        return Err("cargo tree failed".into());
    }
    let active: HashSet<_> = String::from_utf8(tree.stdout)?
        .lines()
        .filter_map(|line| {
            let mut parts = line.split_whitespace();
            Some(format!(
                "{}-{}",
                parts.next()?,
                parts.next()?.trim_start_matches('v')
            ))
        })
        .collect();
    let mut packages = BTreeMap::new();
    for package in metadata["packages"].as_array().ok_or("no packages")? {
        let key = format!(
            "{}-{}",
            package["name"].as_str().ok_or("no name")?,
            package["version"].as_str().ok_or("no version")?
        );
        if package["source"].is_null() || !active.contains(&key) {
            continue;
        }
        packages.insert(key, package);
    }
    let mut index = String::from(
        "# Third-party licenses\n\nGenerated by `cargo run --locked --bin license-notices`.\n\nScope: active direct, transitive, build and development dependencies for x86_64-unknown-linux-gnu with the locked default application features. Other platforms and optional unbuilt features are not approved for distribution. This inventory complements, and does not replace, cargo-deny and the manual native/asset audit in [docs/LICENSE_AUDIT.md](docs/LICENSE_AUDIT.md). Original notices are preserved under LICENSES/; crate licenses are not changed to MIT. For `MIT OR Apache-2.0`, select MIT. For all other expressions comply with a permitted alternative or every AND term. Unicode-3.0 was individually reviewed and explicitly approved on 2026-10-24.\n\nNo bundled fonts, icons, FFmpeg or VOICEVOX. The application reads installed system fonts.\n\n| Crate | Version | Declared license | Original documents |\n|---|---|---|---|\n",
    );
    let mut missing = Vec::new();
    let mut builds = String::from(
        "# Build script inventory\n\nGenerated from Cargo metadata for the active Linux graph. These scripts require manual source review after dependency changes.\n\n| Crate | Script |\n|---|---|\n",
    );
    for (key, package) in &packages {
        let root = Path::new(package["manifest_path"].as_str().ok_or("no manifest")?)
            .parent()
            .ok_or("no parent")?;
        let mut files = Vec::new();
        notices(root, root, 0, &mut files)?;
        files.sort();
        if let Some(file) = package["license_file"].as_str() {
            let file = PathBuf::from(file);
            if !files.contains(&file) {
                files.push(file);
            }
        }
        let mut links = Vec::new();
        for relative in files {
            if relative
                .components()
                .any(|c| !matches!(c, std::path::Component::Normal(_)))
            {
                return Err("unsafe license path".into());
            }
            let target = Path::new("LICENSES").join(key).join(&relative);
            fs::create_dir_all(target.parent().ok_or("no license parent")?)?;
            fs::copy(root.join(&relative), &target)?;
            links.push(format!("[{}]({})", relative.display(), target.display()));
        }
        if links.is_empty() {
            let upstream = Path::new("LICENSES").join(key).join("upstream");
            if upstream.is_dir() {
                let mut documents = Vec::new();
                notices(&upstream, &upstream, 0, &mut documents)?;
                for document in documents {
                    links.push(format!(
                        "[upstream/{}]({})",
                        document.display(),
                        upstream.join(&document).display()
                    ));
                }
            }
            if links.is_empty() {
                missing.push(key.clone());
            }
        }
        if matches!(
            package["name"].as_str(),
            Some("gl_generator" | "khronos_api")
        ) {
            let source = root.join(if package["name"] == "gl_generator" {
                "lib.rs"
            } else {
                "src/lib.rs"
            });
            let source = fs::read_to_string(source)?;
            let mut embedded = source
                .lines()
                .take_while(|line| line.starts_with("//"))
                .collect::<Vec<_>>()
                .join("\n");
            if package["name"] == "khronos_api" {
                for relative in [
                    "api/xml/gl.xml",
                    "api/xml/glx.xml",
                    "api/xml/wgl.xml",
                    "api_egl/api/egl.xml",
                ] {
                    let xml = fs::read_to_string(root.join(relative))?;
                    let comment = if let Some((_, tail)) = xml.split_once("<comment>") {
                        tail.split_once("</comment>").map(|(notice, _)| notice)
                    } else {
                        xml.split_once("<!--")
                            .and_then(|(_, tail)| tail.split_once("-->"))
                            .map(|(notice, _)| notice)
                    }
                    .ok_or("missing Khronos XML license")?;
                    embedded.push_str(&format!("\n\nOriginal {relative} notice:\n{comment}\n"));
                }
            }
            let target = Path::new("LICENSES").join(key).join("NOTICE-EMBEDDED.txt");
            fs::create_dir_all(target.parent().ok_or("no notice parent")?)?;
            fs::write(&target, embedded)?;
            links.push(format!("[embedded notices]({})", target.display()));
        }
        index.push_str(&format!(
            "| {} | {} | {} | {} |\n",
            package["name"].as_str().unwrap_or_default(),
            package["version"].as_str().unwrap_or_default(),
            package["license"]
                .as_str()
                .unwrap_or("UNDECLARED")
                .replace('|', "\\|"),
            links.join(", ")
        ));
        for target in package["targets"].as_array().ok_or("no targets")? {
            if target["kind"]
                .as_array()
                .is_some_and(|a| a.iter().any(|v| v == "custom-build"))
            {
                let path = Path::new(target["src_path"].as_str().ok_or("no build path")?)
                    .strip_prefix(root)?;
                builds.push_str(&format!("| {key} | {} |\n", path.display()));
            }
        }
    }
    let rustc = Command::new("rustc").arg("--version").output()?;
    let rustc = String::from_utf8(rustc.stdout)?;
    let version = rustc
        .split_whitespace()
        .nth(1)
        .ok_or("unknown Rust version")?;
    let sysroot = Command::new("rustc")
        .args(["--print", "sysroot"])
        .output()?;
    let sysroot = PathBuf::from(String::from_utf8(sysroot.stdout)?.trim());
    let doc = sysroot.join("share/doc/rust");
    let target = Path::new("LICENSES").join(format!("rust-stdlib-{version}"));
    fs::create_dir_all(&target)?;
    fs::copy(
        doc.join("COPYRIGHT-library.html"),
        target.join("COPYRIGHT-library.html"),
    )?;
    for license in ["MIT", "Apache-2.0", "BSD-2-Clause", "ISC", "Unicode-3.0"] {
        fs::copy(
            doc.join("licenses").join(format!("{license}.txt")),
            target.join(format!("{license}.txt")),
        )?;
    }
    index.push_str(&format!("\n## Rust standard library\n\nBuilt with `{}`. The [original standard library notices]({}/COPYRIGHT-library.html) and license texts are retained separately. This upstream document is a superset across Rust targets; its SGX/EFI entries do not imply those libraries are linked into this Linux GNU binary. Select the permitted MIT/Apache alternatives where available; Unicode-3.0 is individually approved. See the native audit for dynamic OS components. The Rust compiler, LLVM, rustdoc and documentation fonts are not shipped.\n", rustc.trim(), target.display()));
    index.push_str("\n## Non-bundled Linux audio component\n\nTimeline audio dynamically loads the system `libasound.so.2` (ALSA library, LGPL-2.1-or-later). No ALSA implementation, headers, plugin, or binary is shipped. The independently written Rust ABI wrapper is MIT. Original system-package [copyright notice](LICENSES/system-alsa-lib/COPYRIGHT) and [LGPL 2.1 text](LICENSES/system-alsa-lib/LGPL-2.1.txt) are retained for disclosure; they do not change the crate allowlist. Users may replace the system library and reverse-engineer the application for debugging such modifications. See [the native audit](docs/LICENSE_AUDIT.md) for the LGPL 2.1 section 6(b) shared-library mechanism and pre-release distribution review.\n");
    index.push_str("\n## Optional non-bundled file chooser\n\nThe app may invoke the user-installed Zenity executable to open a system file chooser. No Zenity/GTK executable, library, source, or asset is linked, copied, installed, or shipped. If unavailable, an independently written Rust/egui browser is used. The installed package reports LGPL-2-or-later source headers and LGPL-2.1-or-later COPYING; see [the manual audit](docs/LICENSE_AUDIT.md) and [upstream COPYING](https://github.com/GNOME/zenity/blob/master/COPYING). This separate OS program is outside the crate allowlist. Any future bundling would require a separate distribution review.\n");
    fs::write("THIRD_PARTY_LICENSES.md", index)?;
    fs::create_dir_all("docs")?;
    fs::write("docs/BUILD_SCRIPTS.md", builds)?;
    println!(
        "Inventoried {} active Linux crates; missing original license documents: {}",
        packages.len(),
        missing.len()
    );
    if !missing.is_empty() {
        return Err(format!("Missing original documents: {}", missing.join(", ")).into());
    }
    Ok(())
}
